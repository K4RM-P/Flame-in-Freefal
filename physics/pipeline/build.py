"""Build verified test_point table (parquet + CSV) and coverage report."""
from __future__ import annotations

import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import normalize  # noqa: E402
import split  # noqa: E402
import verify  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
PROC = ROOT / "data" / "processed"


def main() -> None:
    raw = pd.read_csv(PROC / "flex_raw.csv")
    tp = split.apply(verify.apply(normalize.normalize_flex(raw)))
    tp.to_parquet(PROC / "test_points.parquet", index=False)
    tp.to_csv(PROC / "test_points.csv", index=False)
    cov = tp.groupby(["investigation_id", "fuel", "diluent", "split"]).agg(
        n=("id", "size"), verified=("verified", "sum"), with_K=("K_mm2_s", "count"), with_dext=("d_ext_mm", "count"))
    lines = ["# Data coverage (auto-generated by physics/pipeline/build.py)", "",
             f"Total rows: {len(tp)} · verified: {int(tp.verified.sum())} · investigations: {tp.investigation_id.nunique()}", "",
             cov.reset_index().to_markdown(index=False)]
    (PROC / "coverage.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines[:3]))


if __name__ == "__main__":
    main()
